const SEED: &str = "seed.json";
const OWNER: &str = "instance.json";
const PENDING: &str = "building.json";
const DISK: &str = "volume.sparseimage";

#[derive(Serialize, Deserialize)]
struct Seed {
    version: u32,
    location: PathBuf,
    identity: Id,
    backing: Id,
    repo: PathBuf,
    common: PathBuf,
    revision: String,
    context: String,
    indexes: Vec<String>,
    sealed: u64,
    t3: bool,
}

#[derive(Serialize, Deserialize)]
struct Instance {
    version: u32,
    location: PathBuf,
    identity: Id,
    backing: Id,
    common: PathBuf,
    repo: PathBuf,
    revision: String,
    branches: Vec<String>,
    // Paths generated by Git under the repository's worktrees/ directory.
    admins: Vec<(PathBuf, Id)>,
    volume: Inventory,
    removing: bool,
}

// Written before attaching anything. A killed process may leave a mounted
// image and empty/native Git registrations; discard recovery owns only these.
#[derive(Serialize, Deserialize)]
struct Pending {
    directory: PathBuf,
    id: Id,
    backing: Id,
    repo: PathBuf,
    count: usize,
    making_seed: bool,
}
fn record_build(dir: &Path, repo: &Path, count: usize, making_seed: bool) -> Result<()> {
    save(
        &dir.join(PENDING),
        &Pending {
            directory: dir.into(),
            id: identity(dir)?,
            backing: identity(&dir.join(DISK))?,
            repo: repo.into(),
            count,
            making_seed,
        },
    )
}
fn finish_build(dir: &Path) -> Result<()> {
    if dir.join(PENDING).try_exists()? {
        let pending: Pending = read(&dir.join(PENDING))?;
        ensure!(
            pending.directory == dir && pending.id == identity(dir)?,
            "unknown build journal"
        );
        if dir.join(DISK).try_exists()? {
            ensure!(
                pending.backing == identity(&dir.join(DISK))?,
                "journal backing identity changed"
            )
        }
        fs::remove_file(dir.join(PENDING))?;
    }
    Ok(())
}
fn recover_build(dir: &Path, making_seed: bool, discard: bool) -> Result<()> {
    ensure!(
        discard,
        "interrupted image operation: inspect {} and rerun with --discard",
        dir.display()
    );
    let pending: Pending = read(&dir.join(PENDING))?;
    ensure!(
        pending.directory == dir
            && pending.id == identity(dir)?
            && pending.making_seed == making_seed,
        "pending image ownership mismatch"
    );
    limit(pending.count)?;
    let backing = dir.join(DISK);
    let mount = dir.join("mount");
    ensure!(
        entries(dir)?
            .keys()
            .all(|k| [PENDING, "mount", DISK].contains(&k.as_str())),
        "unknown entry in interrupted image"
    );
    if backing.try_exists()? {
        ensure!(
            identity(&backing)? == pending.backing,
            "interrupted image backing replaced"
        );
    }
    let allowed: HashSet<_> = (0..pending.count).map(|i| workdir(&mount, i)).collect();
    let known = list_worktrees(&pending.repo)?
        .into_iter()
        .filter(|w| w.starts_with(&mount))
        .collect::<Vec<_>>();
    ensure!(
        known.iter().all(|w| allowed.contains(w)),
        "another Git checkout was registered on this image"
    );
    detach(&backing, &mount)?;
    remove_empty_mount(&mount)?;
    for w in known {
        checked(
            git_cmd(&pending.repo)
                .args(["worktree", "remove", "--force", "--"])
                .arg(w),
        )?;
    }
    // Branches are preserved: a killed process may not have recorded whether
    // a particular ref was freshly created or advanced by a checkout hook.
    if backing.try_exists()? {
        fs::remove_file(backing)?;
    }
    finish_build(dir)?;
    fs::remove_dir(dir)?;
    Ok(())
}

fn inside(repo: &Path, common: &Path, path: &Path) -> bool {
    path.starts_with(repo) || path.starts_with(common)
}
fn checked_root(repo: &Path, common: &Path, path: &Path) -> Result<PathBuf> {
    let parent = path
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    ensure!(
        !inside(repo, common, &parent.canonicalize()?),
        "put the image outside the source and Git database"
    );
    new_dir(path)
}
fn limit(n: usize) -> Result<()> {
    ensure!((1..=8).contains(&n), "expected 1 to 8 worktrees");
    Ok(())
}
fn list_worktrees(repo: &Path) -> Result<HashSet<PathBuf>> {
    use std::os::unix::ffi::OsStrExt;
    let bytes = checked(git_cmd(repo).args(["worktree", "list", "--porcelain", "-z"]))?;
    Ok(bytes
        .split(|c| *c == 0)
        .filter_map(|record| record.strip_prefix(b"worktree "))
        .map(|path| PathBuf::from(OsStr::from_bytes(path)))
        .collect())
}
fn workdir(mount: &Path, i: usize) -> PathBuf {
    mount.join(format!("work-{}", i + 1))
}
fn index(mount: &Path, i: usize) -> PathBuf {
    mount.join(format!(".index-{}", i + 1))
}
fn payload(mount: &Path, i: usize) -> PathBuf {
    mount.join(format!("payload-{}", i + 1))
}
fn digest(path: &Path) -> Result<String> {
    Ok(hex::encode(Sha256::digest(fs::read(path)?)))
}

fn context(repo: &Path) -> Result<String> {
    let config = checked(git_cmd(repo).args(["config", "--list", "--null"]))?;
    let mut digest = Sha256::new();
    digest.update(git(repo, ["--version"])?);
    ensure!(
        git(
            repo,
            [
                "for-each-ref",
                "--count=1",
                "--format=%(refname)",
                "refs/replace/"
            ]
        )?
        .is_empty(),
        "replacement refs are unsupported for image seeds"
    );
    let common = PathBuf::from(git(
        repo,
        ["rev-parse", "--path-format=absolute", "--git-common-dir"],
    )?);
    ensure!(
        !common.join("info/attributes").is_file(),
        "external Git attributes are unsupported for image seeds"
    );
    for scope in ["GIT_ATTR_GLOBAL", "GIT_ATTR_SYSTEM"] {
        ensure!(
            !Path::new(&git(repo, ["var", scope])?).is_file(),
            "external Git attributes are unsupported for image seeds"
        );
    }
    for row in config
        .split(|&v| v == 0)
        .filter(|r| !r.starts_with(b"branch."))
    {
        let key = row.split(|b| *b == b'\n').next().unwrap_or_default();
        ensure!(
            !key.starts_with(b"includeif.")
                && key != b"extensions.worktreeconfig"
                && key != b"core.sparsecheckout",
            "image seeds require matching full checkouts without conditional Git configuration"
        );
        digest.update(row);
        digest.update([0]);
    }
    Ok(hex::encode(digest.finalize()))
}

// Strip the preparation checkout's admin pointer while keeping its large payload
// on the mounted volume. Git itself removes the empty checkout and registration.
fn unregister_seed(repo: &Path, work: &Path, keep: &Path) -> Result<()> {
    let original = work.join(".git");
    let pointer = keep.join(".git");
    fs::rename(work, keep)?;
    let result = (|| -> Result<()> {
        fs::create_dir(work)?;
        fs::rename(&pointer, &original)?;
        checked(
            git_cmd(repo)
                .args(["worktree", "remove", "--force", "--"])
                .arg(work),
        )?;
        Ok(())
    })();
    if result.is_err() {
        if original.try_exists()? {
            fs::rename(original, &pointer)?;
        }
        if work.try_exists()? {
            fs::remove_dir(work)?;
        }
        fs::rename(keep, work)?;
    }
    result
}

fn build_index(common: &Path, payload: &Path, index: &Path, revision: &str) -> Result<String> {
    let run = |args: &[&str]| -> Result<Vec<u8>> {
        checked(
            git_cmd(payload)
                .env("GIT_INDEX_FILE", index)
                .env("GIT_INDEX_VERSION", "2")
                .args([
                    "-c",
                    "core.hooksPath=/dev/null",
                    "-c",
                    "core.splitIndex=false",
                    "-c",
                    "core.fsmonitor=false",
                    "-c",
                    "core.untrackedCache=false",
                    "-c",
                    "index.skipHash=false",
                    "--git-dir",
                ])
                .arg(common)
                .arg("--work-tree")
                .arg(payload)
                .args(args),
        )
    };
    run(&["read-tree", "--reset", "--no-sparse-checkout", revision])?;
    // Refresh a statless index so Git verifies the payload's tracked contents.
    run(&["update-index", "--really-refresh"])?;
    ensure!(
        run(&["write-tree"])? == run(&["rev-parse", &format!("{revision}^{{tree}}")])?,
        "seed index no longer matches the requested commit"
    );
    digest(index)
}
fn prepare(dir: &Path, revision: &str, count: usize, size: &str, t3: bool) -> Result<()> {
    limit(count)?;
    ensure!(
        !size.starts_with('-') && !size.is_empty(),
        "invalid image size"
    );
    let repo =
        PathBuf::from(git(Path::new("."), ["rev-parse", "--show-toplevel"])?).canonicalize()?;
    let common = PathBuf::from(git(
        &repo,
        ["rev-parse", "--path-format=absolute", "--git-common-dir"],
    )?)
    .canonicalize()?;
    let revision = git(
        &repo,
        [
            "rev-parse",
            "--verify",
            "--end-of-options",
            &format!("{revision}^{{commit}}"),
        ],
    )?;
    context(&repo)?;
    crate::checkout::check_filters(&common, &revision)?;
    if t3 {
        ensure!(
            revision == crate::image_deps::PIN,
            "--t3 requires the audited T3 commit"
        );
    }
    let dir = checked_root(&repo, &common, dir)?;
    let _lock = lock(&dir, true)?;
    let backing = dir.join(DISK);
    let mount = dir.join("mount");
    let work = workdir(&mount, 0);
    let outcome = (|| -> Result<()> {
        format(&backing, size)?;
        record_build(&dir, &repo, 1, true)?;
        attach(&backing, &mount)?;
        checked(
            git_cmd(&repo)
                .args([
                    "-c",
                    "core.hooksPath=/dev/null",
                    "-c",
                    "checkout.workers=4",
                    "worktree",
                    "add",
                    "--quiet",
                    "--detach",
                    "--",
                ])
                .arg(&work)
                .arg(&revision),
        )?;
        if t3 {
            crate::image_deps::install_and_seal(&work, &repo, &revision)?;
        }
        let first = payload(&mount, 0);
        unregister_seed(&repo, &work, &first)?;
        let mut indexes = Vec::with_capacity(count);
        for i in 0..count {
            let p = payload(&mount, i);
            if i > 0 {
                crate::apfs::clone_path(&first, &p)?;
                if t3 {
                    crate::image_deps::repair_payload_links(&first, &p)?;
                }
            }
            indexes.push(build_index(&common, &p, &index(&mount, i), &revision)?);
        }
        let sealed = SystemTime::now().duration_since(UNIX_EPOCH)?.as_secs();
        detach(&backing, &mount)?;
        remove_empty_mount(&mount)?;
        set_mode(&backing, 0o400)?;
        save(
            &dir.join(SEED),
            &Seed {
                version: 1,
                location: dir.clone(),
                identity: identity(&dir)?,
                backing: identity(&backing)?,
                repo: repo.clone(),
                common: common.clone(),
                context: context(&repo)?,
                revision,
                indexes,
                sealed,
                t3,
            },
        )
    })();
    if let Err(err) = outcome {
        let cleanup = (|| -> Result<()> {
            detach(&backing, &mount)?;
            if list_worktrees(&repo)?.contains(&work) {
                checked(
                    git_cmd(&repo)
                        .args(["worktree", "remove", "--force", "--"])
                        .arg(&work),
                )?;
            }
            if backing.try_exists()? {
                fs::remove_file(&backing)?;
            }
            remove_empty_mount(&mount)?;
            finish_build(&dir)?;
            fs::remove_dir(&dir)?;
            Ok(())
        })();
        if let Err(other) = cleanup {
            return Err(err.context(format!(
                "cleanup of {} also failed: {other:#}",
                dir.display()
            )));
        }
        return Err(err);
    }
    finish_build(&dir)
}

fn read_seed(dir: &Path) -> Result<Seed> {
    let s: Seed = read(&dir.join(SEED))?;
    ensure!(
        s.version == 1
            && s.location == dir
            && s.identity == identity(dir)?
            && s.backing == identity(&dir.join(DISK))?,
        "wrong seed directory or backing file"
    );
    limit(s.indexes.len())?;
    ensure!(
        fs::metadata(dir.join(DISK))?.mode() & 0o222 == 0 && attached(&dir.join(DISK))?.is_none(),
        "seed must be detached and read-only"
    );
    Ok(s)
}

fn admin_of(repo: &Path, common: &Path, work: &Path) -> Result<PathBuf> {
    ensure!(
        !fs::symlink_metadata(work)?.is_symlink()
            && fs::symlink_metadata(work.join(".git"))?.is_file(),
        "invalid Git pointer"
    );
    let admin = PathBuf::from(git(work, ["rev-parse", "--absolute-git-dir"])?);
    ensure!(
        admin.canonicalize()? == admin && admin.parent() == Some(&common.join("worktrees")),
        "foreign Git admin directory"
    );
    let reverse = admin.join("gitdir");
    ensure!(
        fs::symlink_metadata(&reverse)?.is_file(),
        "invalid Git admin backlink"
    );
    let back = fs::read_to_string(reverse)?;
    ensure!(
        admin.join(back.trim_end_matches('\n')).canonicalize()? == work.join(".git"),
        "Git backlink mismatch"
    );
    ensure!(
        PathBuf::from(git(
            repo,
            ["rev-parse", "--path-format=absolute", "--git-common-dir"]
        )?)
        .canonicalize()?
            == common,
        "Git repository location changed"
    );
    Ok(admin)
}

fn trust_stats(repo: &Path) -> Result<bool> {
    Ok(git(
        repo,
        [
            "config",
            "--type=bool",
            "--default=true",
            "--get",
            "core.trustctime",
        ],
    )? == "true"
        && git(
            repo,
            [
                "config",
                "--type=bool",
                "--default=false",
                "--get",
                "core.ignorestat",
            ],
        )? == "false"
        && git(
            repo,
            ["config", "--default=default", "--get", "core.checkstat"],
        )? == "default")
}

fn install_index(admin: &Path, work: &Path, saved: &Path, hash: &str, seed: &Seed) -> Result<()> {
    ensure!(
        fs::symlink_metadata(saved)?.is_file() && digest(saved)? == hash,
        "invalid prepared Git index"
    );
    if trust_stats(work)? {
        let mut temp = tempfile::NamedTempFile::new_in(admin)?;
        std::io::copy(&mut fs::File::open(saved)?, &mut temp)?;
        temp.flush()?;
        temp.persist_noclobber(admin.join("index"))?;
        let target = UNIX_EPOCH + Duration::from_secs(seed.sealed + 1);
        if let Ok(delay) = target.duration_since(SystemTime::now()) {
            ensure!(
                delay <= Duration::from_secs(2),
                "clock moved backwards after preparing the image"
            );
            std::thread::sleep(delay);
        }
    } else {
        git(
            work,
            [
                "read-tree",
                "--reset",
                "--no-sparse-checkout",
                &seed.revision,
            ],
        )?;
    }
    Ok(())
}

fn discard_failed_branch(repo: &Path, branch: &str, revision: &str) -> Result<()> {
    let gitref = format!("refs/heads/{branch}");
    if git(
        repo,
        ["for-each-ref", "--format=%(refname) %(objectname)", &gitref],
    )? == format!("{gitref} {revision}")
        && !git(repo, ["worktree", "list", "--porcelain", "-z"])?
            .split('\0')
            .any(|f| f == format!("branch {gitref}"))
    {
        git(repo, ["update-ref", "-d", &gitref, revision])?;
    }
    Ok(())
}

fn create_refs(seed: &Seed, branches: &[String]) -> Result<()> {
    use std::process::Stdio;
    // All names were verified with check-ref-format. A create-only transaction
    // proves ownership even if another process tries to create the same names.
    let mut input = String::from("start\n");
    for b in branches {
        input.push_str(&format!("create refs/heads/{b} {}\n", seed.revision));
    }
    input.push_str("prepare\ncommit\n");
    let mut child = git_cmd(&seed.repo)
        .args(["update-ref", "--stdin", "-m", "worktree-fast image create"])
        .stdin(Stdio::piped())
        .stdout(Stdio::null())
        .stderr(Stdio::piped())
        .spawn()?;
    child
        .stdin
        .take()
        .context("missing Git transaction pipe")?
        .write_all(input.as_bytes())?;
    let out = child.wait_with_output()?;
    ensure!(
        out.status.success(),
        "branch creation failed: {}",
        String::from_utf8_lossy(&out.stderr).trim_end()
    );
    Ok(())
}

fn workers<T: Send>(
    range: std::ops::Range<usize>,
    operation: impl Fn(usize) -> Result<T> + Sync,
) -> Vec<Result<T>> {
    std::thread::scope(|scope| {
        let handles = range
            .map(|i| {
                scope.spawn({
                    let op = &operation;
                    move || op(i)
                })
            })
            .collect::<Vec<_>>();
        handles
            .into_iter()
            .map(|h| {
                h.join()
                    .unwrap_or_else(|_| Err(anyhow::anyhow!("image worker panicked")))
            })
            .collect()
    })
}

fn register(seed: &Seed, mount: &Path, i: usize, branch: &str) -> Result<()> {
    let work = workdir(mount, i);
    let p = payload(mount, i);
    ensure!(
        p.canonicalize()? == p
            && fs::symlink_metadata(p.join(".git"))
                .is_err_and(|e| e.kind() == std::io::ErrorKind::NotFound),
        "unexpected source payload"
    );
    checked(
        git_cmd(&seed.repo)
            .args(["worktree", "add", "--quiet", "--no-checkout", "--"])
            .arg(&work)
            .arg(branch),
    )?;
    Ok(())
}

fn adopt(
    mount: &Path,
    i: usize,
    seed: &Seed,
    branch: &str,
    hooks: &std::sync::Mutex<()>,
    tools: Option<&crate::image_deps::Toolchain>,
) -> Result<(PathBuf, Id)> {
    let p = payload(mount, i);
    let work = workdir(mount, i);
    let head = git(&work, ["rev-parse", "HEAD", "--symbolic-full-name", "HEAD"])?;
    ensure!(
        head == format!("{}\nrefs/heads/{branch}", seed.revision),
        "branch changed while preparing {}",
        work.display()
    );
    let ptr = work.join(".git");
    fs::rename(&ptr, p.join(".git"))?;
    if let Err(err) = fs::rename(&p, &work) {
        fs::rename(p.join(".git"), &ptr)?;
        return Err(err.into());
    }
    let admin = admin_of(&seed.repo, &seed.common, &work)?;
    install_index(&admin, &work, &index(mount, i), &seed.indexes[i], seed)?;
    {
        // A user hook may write shared repository configuration. Serialize only
        // this callback; per-checkout index and dependency activation can overlap.
        let _guard = hooks
            .lock()
            .map_err(|_| anyhow::anyhow!("checkout hook lock poisoned"))?;
        let hook = git_cmd(&work)
            .args([
                "hook",
                "run",
                "--ignore-missing",
                "post-checkout",
                "--",
                &"0".repeat(seed.revision.len()),
                &seed.revision,
                "1",
            ])
            .output()?;
        std::io::stderr().write_all(&hook.stdout)?;
        std::io::stderr().write_all(&hook.stderr)?;
        ensure!(hook.status.success(), "post-checkout hook failed");
    }
    if let Some(tools) = tools {
        crate::image_deps::activate_with(&work, &seed.repo, &seed.revision, tools)?;
    }

    Ok((admin.clone(), identity(&admin)?))
}

fn create(seed_path: &Path, instance: &Path, branches: &[String]) -> Result<()> {
    let (seed_path, _locked) = lock(seed_path, false)?;
    let seed = read_seed(&seed_path)?;
    ensure!(
        branches.len() == seed.indexes.len(),
        "expected {} new branch name(s)",
        seed.indexes.len()
    );
    ensure!(
        branches.iter().collect::<HashSet<_>>().len() == branches.len(),
        "duplicate branch name"
    );
    ensure!(
        seed.context == context(&seed.repo)?,
        "Git checkout configuration changed; prepare a new seed"
    );
    for b in branches {
        ensure!(
            git(&seed.repo, ["check-ref-format", "--branch", b])? == *b,
            "invalid branch name"
        );
    }
    let parent = instance
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or(Path::new("."))
        .canonicalize()?;
    ensure!(
        !parent.starts_with(&seed_path),
        "instance cannot be created inside the seed"
    );
    let dir = checked_root(&seed.repo, &seed.common, instance)?;
    let _instance_lock = lock(&dir, true)?;
    let backing = dir.join(DISK);
    let mount = dir.join("mount");
    let mut own_refs = false;
    let outcome = (|| -> Result<()> {
        crate::apfs::clone_path(&seed_path.join(DISK), &backing)?;
        set_mode(&backing, 0o600)?;
        record_build(&dir, &seed.repo, branches.len(), false)?;
        let tools = std::thread::scope(|scope| -> Result<_> {
            let refs = scope.spawn(|| create_refs(&seed, branches));
            let probe = seed
                .t3
                .then(|| scope.spawn(|| crate::image_deps::activation_toolchain(&seed.repo)));
            let mounted = attach(&backing, &mount);
            refs.join()
                .map_err(|_| anyhow::anyhow!("branch reservation worker panicked"))??;
            own_refs = true;
            mounted?;
            probe
                .map(|h| {
                    h.join()
                        .map_err(|_| anyhow::anyhow!("toolchain probe panicked"))?
                })
                .transpose()
        })?;
        // The first registration can upgrade Git's repository format for
        // relative worktree paths. Let it finish before its siblings contend.
        register(&seed, &mount, 0, &branches[0])?;
        let register_peer = |i: usize| register(&seed, &mount, i, &branches[i]);
        // Git returns 1 when no hook is configured. If an older Git lacks
        // hook discovery or a ref callback is installed, keep ref side effects
        // in order while still parallelizing each checkout's installation.
        let hook_free = branches.len() < 3
            || git_cmd(&seed.repo)
                .args(["hook", "list", "reference-transaction"])
                .output()?
                .status
                .code()
                == Some(1);
        let results = if hook_free {
            workers(1..branches.len(), register_peer)
        } else {
            (1..branches.len()).map(register_peer).collect()
        };
        for (i, result) in (1..branches.len()).zip(results) {
            if let Err(err) = result {
                // Apple Git can observe a peer's admin directory between mkdir
                // and writing commondir. All writers have joined here. Retry
                // only that read race after proving this slot is still unused.
                let detail = format!("{err:#}");
                let work = workdir(&mount, i);
                if !(hook_free
                    && detail.contains("failed to read")
                    && detail.contains("worktrees/")
                    && detail.contains("/commondir")
                    && !list_worktrees(&seed.repo)?.contains(&work)
                    && (!work.try_exists()?
                        || (work.canonicalize()? == work && entries(&work)?.is_empty())))
                {
                    return Err(err.context(format!("registering {}", branches[i])));
                }
                register_peer(i)?;
            }
        }
        let hooks = std::sync::Mutex::new(());
        let admins = workers(0..branches.len(), |i| {
            adopt(&mount, i, &seed, &branches[i], &hooks, tools.as_ref())
        })
        .into_iter()
        .collect::<Result<Vec<_>>>()?;
        save(
            &dir.join(OWNER),
            &Instance {
                version: 1,
                location: dir.clone(),
                identity: identity(&dir)?,
                backing: identity(&backing)?,
                common: seed.common.clone(),
                repo: seed.repo.clone(),
                revision: seed.revision.clone(),
                branches: branches.to_vec(),
                admins,
                volume: entries(&mount)?,
                removing: false,
            },
        )
    })();
    if let Err(err) = outcome {
        let cleanup = (|| -> Result<()> {
            detach(&backing, &mount)?;
            if own_refs {
                // An interrupted Git command can register a checkout despite
                // exiting with an error. Discover all registrations in our new
                // private volume before releasing any refs.
                let listed = list_worktrees(&seed.repo)?;
                for i in 0..branches.len() {
                    let work = workdir(&mount, i);
                    if listed.contains(&work) {
                        checked(
                            git_cmd(&seed.repo)
                                .args(["worktree", "remove", "--force", "--"])
                                .arg(work),
                        )?;
                    }
                }
                for branch in branches {
                    discard_failed_branch(&seed.repo, branch, &seed.revision)?;
                }
            }
            if backing.try_exists()? {
                fs::remove_file(&backing)?;
            }
            remove_empty_mount(&mount)?;
            finish_build(&dir)?;
            fs::remove_dir(&dir)?;
            Ok(())
        })();
        if let Err(other) = cleanup {
            return Err(err.context(format!(
                "cleanup of {} also failed: {other:#}",
                dir.display()
            )));
        }
        return Err(err);
    }
    finish_build(&dir)?;
    for i in 0..branches.len() {
        println!("{}", workdir(&mount, i).display());
    }
    Ok(())
}

fn remove(dir: &Path, discard: bool) -> Result<()> {
    let (dir, _lock) = lock(dir, true)?;
    let file = dir.join(OWNER);
    if !file.try_exists()? && dir.join(PENDING).try_exists()? {
        return recover_build(&dir, false, discard);
    }
    let mut owner: Instance = read(&file)?;
    ensure!(
        owner.version == 1
            && owner.location == dir
            && owner.identity == identity(&dir)?
            && owner.admins.len() == owner.branches.len(),
        "wrong instance directory or manifest"
    );
    limit(owner.admins.len())?;
    finish_build(&dir)?;
    let contents = entries(&dir)?;
    ensure!(
        contents
            .keys()
            .all(|k| [OWNER, DISK, "mount"].contains(&k.as_str())),
        "unknown files in instance directory"
    );
    let backing = dir.join(DISK);
    let mount = dir.join("mount");
    if backing.try_exists()? {
        ensure!(
            owner.backing == identity(&backing)?,
            "backing file was replaced"
        );
    }
    let listed = list_worktrees(&owner.repo)?;
    let works: Vec<_> = (0..owner.branches.len())
        .map(|i| workdir(&mount, i))
        .collect();
    ensure!(
        listed
            .iter()
            .all(|w| !w.starts_with(&mount) || works.contains(w)),
        "another registered Git worktree is inside the mounted image"
    );
    if !owner.removing && !mounted(&mount)? {
        // A restart or manual eject may have detached a live workspace.
        // Inspect its actual backing file before considering disposal.
        ensure!(attached(&backing)?.is_none(), "image is attached elsewhere");
        remove_empty_mount(&mount)?;
        attach(&backing, &mount)?;
    }
    if mounted(&mount)? {
        verify_mount(&backing, &mount)?;
        // Never detach an unknown volume or drop unrelated data placed next to
        // the worktrees. Inside each worktree, Git's normal dirty rules apply.
        let mut expected = owner.volume.clone();
        for (i, work) in works.iter().enumerate() {
            if !listed.contains(work) {
                // Native Git may have removed a member. It must have retired
                // both the checkout and its original admin directory.
                ensure!(
                    !work.try_exists()? && !owner.admins[i].0.try_exists()?,
                    "worktree was moved or replaced: {}",
                    work.display()
                );
                expected.remove(&format!("work-{}", i + 1));
            }
        }
        let volume = entries(&mount)?;
        // Remount can assign the owned image a new device number; its
        // in-volume inode identities remain stable.
        ensure!(
            volume.len() == expected.len()
                && volume
                    .iter()
                    .all(|(name, (_, ino))| expected.get(name).is_some_and(|(_, old)| ino == old)),
            "unexpected or replaced file at volume root"
        );
        for (i, work) in works.iter().enumerate() {
            if !listed.contains(work) {
                continue;
            }

            let admin = admin_of(&owner.repo, &owner.common, work)?;
            ensure!(
                owner.admins[i] == (admin.clone(), identity(&admin)?),
                "worktree registration replaced"
            );
            ensure!(
                !admin.join("locked").try_exists()?,
                "worktree is locked: {}",
                work.display()
            );
            if !discard {
                ensure!(
                    checked(git_cmd(work).args([
                        "-c",
                        "core.fsmonitor=false",
                        "status",
                        "--porcelain=v1",
                        "--untracked-files=all",
                        "--ignore-submodules=none"
                    ]))?
                    .is_empty(),
                    "dirty worktree {}; commit changes or pass --discard",
                    work.display()
                );
                let is_detached = git(work, ["rev-parse", "--abbrev-ref", "HEAD"])? == "HEAD";
                ensure!(
                    !is_detached || git(work, ["rev-parse", "HEAD"])? == owner.revision,
                    "protect the detached HEAD on a branch or pass --discard"
                );
            }
        }
        owner.removing = true;
        save(&file, &owner)?;
    } else {
        ensure!(
            owner.removing,
            "expected the instance to be mounted; inspect its backing image before removal"
        );
    }
    detach(&backing, &mount)?;
    // The real payload stays in the backing file until all registrations have
    // been removed. A busy detach simply leaves a live instance for retry.
    if mount.try_exists()? {
        ensure!(
            entries(&mount)?.is_empty(),
            "unexpected files under the idle mountpoint"
        );
    }
    for (i, work) in works.iter().enumerate() {
        let (admin, expected) = &owner.admins[i];
        if listed.contains(work) {
            ensure!(
                !work.try_exists()?
                    && admin.parent() == Some(&owner.common.join("worktrees"))
                    && identity(admin)? == *expected
                    && !admin.join("locked").try_exists()?,
                "registration ownership changed"
            );
            checked(
                git_cmd(&owner.repo)
                    .args(["worktree", "remove", "--force", "--"])
                    .arg(work),
            )?;
        }
    }
    if backing.try_exists()? {
        fs::remove_file(&backing)?;
    }
    remove_empty_mount(&mount)?;
    fs::remove_file(file)?;
    fs::remove_dir(dir)?;
    Ok(())
}

fn retire(dir: &Path, discard: bool) -> Result<()> {
    let (dir, _lock) = lock(dir, true)?;
    if !dir.join(SEED).try_exists()? && dir.join(PENDING).try_exists()? {
        return recover_build(&dir, true, discard);
    }
    read_seed(&dir)?;
    finish_build(&dir)?;
    ensure!(
        entries(&dir)?.len() == 2,
        "unexpected files in seed directory"
    );
    fs::remove_file(dir.join(DISK))?;
    fs::remove_file(dir.join(SEED))?;
    fs::remove_dir(dir)?;
    Ok(())
}

pub(super) fn run(args: &[OsString]) -> Result<()> {
    match args.first().and_then(|x| x.to_str()) {
        Some("prepare") if args.len() >= 2 => {
            let mut opts = args[2..].iter();
            let mut revision = "HEAD";
            let mut count = 1;
            let mut size = None;
            let mut t3 = false;
            while let Some(key) = opts.next() {
                if key == "--t3" {
                    t3 = true;
                    continue;
                }
                let value = opts
                    .next()
                    .and_then(|x| x.to_str())
                    .context("expected option value")?;
                match key.to_str() {
                    Some("--revision") => revision = value,
                    Some("--count") => count = value.parse()?,
                    Some("--size") => size = Some(value),
                    _ => bail!("unknown image prepare option"),
                }
            }
            prepare(
                Path::new(&args[1]),
                revision,
                count,
                size.unwrap_or(if t3 { "32g" } else { "8g" }),
                t3,
            )
        }
        Some("create") if args.len() >= 4 => {
            let branches = args[3..]
                .iter()
                .map(|b| {
                    b.to_str()
                        .map(str::to_owned)
                        .context("expected Unicode branch name")
                })
                .collect::<Result<Vec<_>>>()?;
            create(Path::new(&args[1]), Path::new(&args[2]), &branches)
        }
        Some("remove") if args.len() == 2 || (args.len() == 3 && args[2] == "--discard") => {
            remove(Path::new(&args[1]), args.len() == 3)
        }
        Some("retire") if args.len() == 2 || (args.len() == 3 && args[2] == "--discard") => {
            retire(Path::new(&args[1]), args.len() == 3)
        }
        _ => bail!("{}", super::USAGE),
    }
}
